CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE reserva
    ADD CONSTRAINT ex_reserva_sem_sobreposicao
    EXCLUDE USING gist (id_sala WITH =, tsrange(inicio, fim, '[)') WITH &&)
        WHERE (status = 'ATIVO');

CREATE TABLE reserva_historico (
                                   id_historico    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   id_reserva      BIGINT       NOT NULL,
                                   status_anterior VARCHAR(20)  NOT NULL,
                                   status_novo     VARCHAR(20)  NOT NULL,
                                   motivo          VARCHAR(50)  NOT NULL,
                                   criado_em       TIMESTAMP    NOT NULL,
                                   CONSTRAINT fk_historico_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
                                   CONSTRAINT ck_historico_status_anterior CHECK (status_anterior IN ('PENDENTE', 'ATIVO', 'CANCELADO', 'FINALIZADO')),
                                   CONSTRAINT ck_historico_status_novo CHECK (status_novo IN ('PENDENTE', 'ATIVO', 'CANCELADO', 'FINALIZADO'))
);

CREATE INDEX idx_historico_reserva ON reserva_historico (id_reserva);
