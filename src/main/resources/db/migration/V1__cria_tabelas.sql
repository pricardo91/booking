CREATE TABLE usuario (
                         id_usuario    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome          VARCHAR(100) NOT NULL,
                         email         VARCHAR(255) NOT NULL,
                         cpf           VARCHAR(11)  NOT NULL,
                         status        VARCHAR(20)  NOT NULL,
                         cadastrado_em TIMESTAMP    NOT NULL,
                         atualizado_em TIMESTAMP,
                         CONSTRAINT uk_usuario_email UNIQUE (email),
                         CONSTRAINT uk_usuario_cpf UNIQUE (cpf),
                         CONSTRAINT ck_usuario_status CHECK (status IN ('ATIVO', 'INATIVO'))
);

CREATE TABLE sala (
                      id_sala       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      nome          VARCHAR(100) NOT NULL,
                      capacidade    INTEGER      NOT NULL,
                      status        VARCHAR(20)  NOT NULL,
                      cadastrado_em TIMESTAMP    NOT NULL,
                      atualizado_em TIMESTAMP,
                      CONSTRAINT uk_sala_nome UNIQUE (nome),
                      CONSTRAINT ck_sala_capacidade CHECK (capacidade >= 1),
                      CONSTRAINT ck_sala_status CHECK (status IN ('ATIVA', 'INATIVA'))
);

CREATE TABLE reserva (
                         id_reserva    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_usuario    BIGINT      NOT NULL,
                         id_sala       BIGINT      NOT NULL,
                         status        VARCHAR(20) NOT NULL,
                         inicio        TIMESTAMP   NOT NULL,
                         fim           TIMESTAMP   NOT NULL,
                         cadastrado_em TIMESTAMP   NOT NULL,
                         atualizado_em TIMESTAMP,
                         CONSTRAINT fk_reserva_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
                         CONSTRAINT fk_reserva_sala FOREIGN KEY (id_sala) REFERENCES sala (id_sala),
                         CONSTRAINT ck_reserva_status CHECK (status IN ('PENDENTE', 'ATIVO', 'CANCELADO', 'FINALIZADO')),
                         CONSTRAINT ck_reserva_intervalo CHECK (fim > inicio)
);

CREATE INDEX idx_reserva_id_sala ON reserva (id_sala);
CREATE INDEX idx_reserva_id_usuario ON reserva (id_usuario);
CREATE INDEX idx_reserva_status ON reserva (status);
